"""Ensure standalone bundle, source module, and license are shipped."""
from pathlib import Path
import unittest
ROOT=Path(__file__).resolve().parents[1]
class DataTablesStaticTests(unittest.TestCase):
 def test_data_module_is_bundled(self):
  html=(ROOT/'index.html').read_text(encoding='utf-8')
  src=(ROOT/'src/data-tables.js').read_text(encoding='utf-8')
  self.assertIn('<script id="mathstudio-data-tables">',html)
  self.assertIn(src,html)
  self.assertIn('id="data-panel"',html)
  self.assertIn('mathstudio-tables-v1',html)
  matrix=(ROOT/'src/matrix-tools.js').read_text(encoding='utf-8').rstrip('\n')
  self.assertIn('<script id="promath-matrix-tools">',html)
  self.assertIn(matrix,html)
  self.assertIn('id="mat-grid"',matrix)
  self.assertIn('id="mat-b-grid"',matrix)
  self.assertIn('id="mat-rhs-grid"',matrix)
  self.assertIn('id="mat-solve"',matrix)
  self.assertIn('id="mat-lu"',matrix)
  self.assertIn('id="mat-lu-factor"',matrix)
  self.assertIn('function lu(A)',matrix)
  self.assertIn('function qr(A)',matrix)
  self.assertIn('id="mat-qr"',matrix)
  self.assertIn('id="mat-qr-factor"',matrix)
  self.assertIn('function leastSquares(A,b)',matrix)
  self.assertIn('id="mat-least-squares"',matrix)
  self.assertIn('M.matrixTools={validate,determinant,transpose,inverse,add,subtract,multiply',matrix)
  ode=(ROOT/'src/ode-tools.js').read_text(encoding='utf-8').rstrip('\n')
  self.assertIn('<script id="promath-ode-tools">',html)
  self.assertIn(ode,html)
  self.assertIn('id="ode-run"',ode)
  fft=(ROOT/'src/fft-tools.js').read_text(encoding='utf-8').rstrip('\n')
  self.assertIn('<script id="promath-fft-tools">',html)
  self.assertIn(fft,html)
  self.assertIn('id="fft-run"',fft)
  self.assertIn('M.fftTools={fft,parse,analyze}',fft)
  project=(ROOT/'src/project-schema.js').read_text(encoding='utf-8').rstrip('\n')
  self.assertIn('<script id="promath-project-schema">',html)
  self.assertIn(project,html)
  self.assertIn('window.MathStudio.projectSchema = {migrate}',project)
  self.assertIn('Saeedmsalehi1990@gmail.com',html)
  self.assertIn('MIT License',(ROOT/'LICENSE').read_text())

 def test_workspace_tasks_module_matches_standalone_bundle(self):
  html=(ROOT/'index.html').read_text(encoding='utf-8')
  source=(ROOT/'src/workspace-tasks.js').read_text(encoding='utf-8').rstrip('\n')
  marker='<script id="promath-workspace-tasks">\n'
  self.assertIn(marker,html)
  embedded=html.split(marker,1)[1].split('</script>',1)[0].rstrip('\n')
  self.assertEqual(embedded,source,'Rebuild index.html with python scripts/build.py when task UI changes')
  self.assertIn("['precision','High precision'",source)
